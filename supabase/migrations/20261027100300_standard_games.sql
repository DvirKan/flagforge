-- FLAGFORGE · persisted standard games for signed-in players.
-- Guests never reach these tables. All writes go through service_role-only functions that lock the session
-- row, so each question is answered exactly once, in order, and time/score come from database timestamps.

create or replace function public.uuid_array_distinct_count(p uuid[])
returns integer
language sql
immutable
set search_path = ''
as $$
  select count(distinct x)::integer from unnest(p) as x;
$$;

create table public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  difficulty text not null,
  status text not null default 'active',
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  total_questions smallint not null,
  correct_count smallint not null default 0,
  score integer not null default 0,
  elapsed_ms bigint,
  created_at timestamptz not null default now(),
  constraint game_sessions_difficulty_valid check (difficulty in ('easy', 'medium', 'hard')),
  constraint game_sessions_status_valid check (status in ('active', 'completed', 'abandoned')),
  constraint game_sessions_total_range check (total_questions between 1 and 50),
  constraint game_sessions_correct_range check (correct_count between 0 and total_questions),
  constraint game_sessions_completion_consistent check (
    (status = 'completed') = (completed_at is not null and elapsed_ms is not null)
  )
);

create index game_sessions_user_started_idx on public.game_sessions (user_id, started_at desc);
create index game_sessions_user_status_idx on public.game_sessions (user_id, status);

create table public.game_session_questions (
  session_id uuid not null references public.game_sessions (id) on delete cascade,
  position smallint not null,
  country_id uuid not null references public.countries (id),
  option_ids uuid[] not null,
  correct_index smallint not null,
  presented_at timestamptz,
  answered_at timestamptz,
  selected_index smallint,
  is_correct boolean,
  points integer,
  primary key (session_id, position),
  constraint gsq_position_positive check (position >= 1),
  constraint gsq_four_options check (cardinality(option_ids) = 4 and public.uuid_array_distinct_count(option_ids) = 4),
  constraint gsq_correct_index_range check (correct_index between 0 and 3),
  constraint gsq_correct_option_matches check (option_ids[correct_index + 1] = country_id),
  constraint gsq_selected_index_range check (selected_index is null or selected_index between 0 and 3),
  constraint gsq_answer_complete check (
    (answered_at is null and selected_index is null and is_correct is null and points is null)
    or (answered_at is not null and selected_index is not null and is_correct is not null and points is not null
        and presented_at is not null)
  )
);

create unique index gsq_session_country_key on public.game_session_questions (session_id, country_id);
create index gsq_country_idx on public.game_session_questions (country_id);

alter table public.game_sessions enable row level security;
alter table public.game_session_questions enable row level security;
revoke all on public.game_sessions from anon, authenticated;
revoke all on public.game_session_questions from anon, authenticated;

-- Players can read their own session summaries. Question rows (which hold the correct answer) are not
-- readable by clients at all; answered history is exposed through my_answered_questions().
grant select on public.game_sessions to authenticated;
create policy "game_sessions: owner can read"
on public.game_sessions for select
to authenticated
using (user_id = (select auth.uid()));

-- ── scoring (mirrors src/lib/game/scoring.ts; parity is covered by integration tests) ──
create or replace function public.answer_points(p_correct boolean, p_response_ms bigint)
returns integer
language sql
immutable
set search_path = ''
as $$
  select case
    when not p_correct then 0
    else 100 + round(50 * (1 - least(greatest(p_response_ms, 0), 15000)::numeric / 15000))::integer
  end;
$$;

-- ── start ────────────────────────────────────────────────────────────────────
-- p_questions: [{ "country": "JP", "options": ["JP","KR","CN","VN"] }, ...] generated by the server engine.
create or replace function public.start_standard_game(p_user_id uuid, p_difficulty text, p_questions jsonb)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session uuid;
  v_count integer := jsonb_array_length(p_questions);
  v_item jsonb;
  v_pos integer := 0;
  v_country uuid;
  v_options uuid[];
  v_correct integer;
begin
  if p_user_id is null or not exists (select 1 from public.profiles where id = p_user_id) then
    raise exception 'unknown_user' using errcode = 'PT404';
  end if;
  if p_difficulty not in ('easy', 'medium', 'hard') then
    raise exception 'invalid_difficulty' using errcode = 'PT400';
  end if;
  if v_count < 1 or v_count > 50 then
    raise exception 'invalid_question_count' using errcode = 'PT400';
  end if;
  -- Abuse guard: at most 60 games started per user per hour.
  if (select count(*) from public.game_sessions
      where user_id = p_user_id and started_at > now() - interval '1 hour') >= 60 then
    raise exception 'rate_limited' using errcode = 'PT429';
  end if;

  update public.game_sessions set status = 'abandoned'
  where user_id = p_user_id and status = 'active';

  insert into public.game_sessions (user_id, difficulty, total_questions)
  values (p_user_id, p_difficulty, v_count)
  returning id into v_session;

  for v_item in select * from jsonb_array_elements(p_questions) loop
    v_pos := v_pos + 1;
    select id into v_country from public.countries where iso_code = v_item ->> 'country';
    if v_country is null then
      raise exception 'unknown_country' using errcode = 'PT400';
    end if;
    select array_agg(c.id order by o.ord) into v_options
    from jsonb_array_elements_text(v_item -> 'options') with ordinality as o(iso, ord)
    join public.countries c on c.iso_code = o.iso;
    if v_options is null or cardinality(v_options) <> 4 then
      raise exception 'invalid_options' using errcode = 'PT400';
    end if;
    v_correct := array_position(v_options, v_country);
    if v_correct is null then
      raise exception 'correct_answer_missing' using errcode = 'PT400';
    end if;
    insert into public.game_session_questions (session_id, position, country_id, option_ids, correct_index, presented_at)
    values (v_session, v_pos, v_country, v_options, v_correct - 1, case when v_pos = 1 then now() end);
  end loop;

  return v_session;
end;
$$;

revoke execute on function public.start_standard_game(uuid, text, jsonb) from public, anon, authenticated;
grant execute on function public.start_standard_game(uuid, text, jsonb) to service_role;

-- ── answer ───────────────────────────────────────────────────────────────────
-- Applies p_choice to question p_position. Fails with 'conflict' unless p_position is exactly the next
-- unanswered question, so retries and double submissions cannot change or skip answers.
create or replace function public.answer_standard_question(p_user_id uuid, p_session_id uuid, p_position integer, p_choice integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.game_sessions%rowtype;
  v_question public.game_session_questions%rowtype;
  v_next_position integer;
  v_correct boolean;
  v_points integer;
  v_now timestamptz := clock_timestamp();
begin
  if p_choice is null or p_choice < 0 or p_choice > 3 then
    raise exception 'invalid_choice' using errcode = 'PT400';
  end if;

  select * into v_session from public.game_sessions where id = p_session_id for update;
  if not found or v_session.user_id is distinct from p_user_id then
    raise exception 'session_not_found' using errcode = 'PT404';
  end if;
  if v_session.status <> 'active' then
    raise exception 'conflict' using errcode = 'PT409';
  end if;
  if v_session.started_at < now() - interval '2 hours' then
    update public.game_sessions set status = 'abandoned' where id = p_session_id;
    raise exception 'session_expired' using errcode = 'PT410';
  end if;

  select min(position) into v_next_position
  from public.game_session_questions
  where session_id = p_session_id and answered_at is null;

  if v_next_position is null or v_next_position <> p_position then
    raise exception 'conflict' using errcode = 'PT409';
  end if;

  select * into v_question from public.game_session_questions
  where session_id = p_session_id and position = p_position;

  v_correct := (p_choice = v_question.correct_index);
  v_points := public.answer_points(
    v_correct,
    (extract(epoch from (v_now - coalesce(v_question.presented_at, v_now))) * 1000)::bigint
  );

  update public.game_session_questions
  set answered_at = v_now, selected_index = p_choice, is_correct = v_correct, points = v_points
  where session_id = p_session_id and position = p_position;

  update public.game_session_questions
  set presented_at = v_now
  where session_id = p_session_id and position = p_position + 1;

  if p_position = v_session.total_questions then
    update public.game_sessions s
    set status = 'completed',
        completed_at = v_now,
        elapsed_ms = (extract(epoch from (v_now - s.started_at)) * 1000)::bigint,
        correct_count = (select count(*) from public.game_session_questions q where q.session_id = s.id and q.is_correct),
        score = (select coalesce(sum(points), 0) from public.game_session_questions q where q.session_id = s.id)
    where s.id = p_session_id
    returning * into v_session;
  end if;

  return jsonb_build_object(
    'correct', v_correct,
    'correct_index', v_question.correct_index,
    'country', (select iso_code from public.countries where id = v_question.country_id),
    'points', v_points,
    'completed', v_session.status = 'completed',
    'difficulty', v_session.difficulty,
    'correct_count', v_session.correct_count,
    'score', v_session.score,
    'elapsed_ms', v_session.elapsed_ms
  );
end;
$$;

revoke execute on function public.answer_standard_question(uuid, uuid, integer, integer) from public, anon, authenticated;
grant execute on function public.answer_standard_question(uuid, uuid, integer, integer) to service_role;

-- Server-side read of a question's options + correct country for building views (never exposed to clients).
create or replace function public.standard_game_question(p_user_id uuid, p_session_id uuid, p_position integer)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'position', q.position,
    'total', s.total_questions,
    'country', c.iso_code,
    'options', (select jsonb_agg(oc.iso_code order by o.ord)
                from unnest(q.option_ids) with ordinality as o(id, ord)
                join public.countries oc on oc.id = o.id),
    'selected_index', q.selected_index,
    'is_correct', q.is_correct
  )
  from public.game_session_questions q
  join public.game_sessions s on s.id = q.session_id
  join public.countries c on c.id = q.country_id
  where q.session_id = p_session_id and q.position = p_position and s.user_id = p_user_id;
$$;

revoke execute on function public.standard_game_question(uuid, uuid, integer) from public, anon, authenticated;
grant execute on function public.standard_game_question(uuid, uuid, integer) to service_role;

-- Answered questions only (correct answers of unanswered questions are never returned). Runs as the caller.
create or replace function public.my_answered_questions(p_session_id uuid)
returns table (question_position smallint, iso_code text, selected_index smallint, is_correct boolean, points integer, answered_at timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select q.position, c.iso_code, q.selected_index, q.is_correct, q.points, q.answered_at
  from public.game_session_questions q
  join public.game_sessions s on s.id = q.session_id
  join public.countries c on c.id = q.country_id
  where q.session_id = p_session_id
    and s.user_id = (select auth.uid())
    and q.answered_at is not null
  order by q.position;
$$;

revoke execute on function public.my_answered_questions(uuid) from public, anon;
grant execute on function public.my_answered_questions(uuid) to authenticated, service_role;

-- Full review of a completed game (server-side, for the results screen). Returns nothing for active games.
create or replace function public.standard_game_review(p_user_id uuid, p_session_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'position', q.position,
      'country', c.iso_code,
      'options', (select jsonb_agg(oc.iso_code order by o.ord)
                  from unnest(q.option_ids) with ordinality as o(id, ord)
                  join public.countries oc on oc.id = o.id),
      'selected_index', q.selected_index,
      'is_correct', q.is_correct
    ) order by q.position), '[]'::jsonb)
  from public.game_session_questions q
  join public.game_sessions s on s.id = q.session_id
  join public.countries c on c.id = q.country_id
  where q.session_id = p_session_id and s.user_id = p_user_id and s.status = 'completed';
$$;

revoke execute on function public.standard_game_review(uuid, uuid) from public, anon, authenticated;
grant execute on function public.standard_game_review(uuid, uuid) to service_role;
